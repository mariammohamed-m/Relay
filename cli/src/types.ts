/** Schema version for {@link RelayData}; bump on any breaking shape change. */
export const SCHEMA_VERSION = 4;

/**
 * A `Task` as embedded in the compiled snapshot, with one field the CLI
 * derives at compile time rather than storing in `task.json`: Bob edits
 * artifact files directly on disk without going through the CLI, so a
 * task's true "last touched" time has to be computed as the max of
 * `task.json`'s own `updatedAt` and every artifact file's mtime.
 */
export interface CompiledTask extends Task {
  lastEditedAt: string;
}

/** Aggregate duration comparison for one stage, relay run vs. manual baseline. */
export interface StageImpact {
  stage: StageId;
  /** Median seconds spent in this stage across relay runs, or null if no data. */
  relaySec: number | null;
  /** Median seconds spent in this stage across baseline runs, or null if no data. */
  baselineSec: number | null;
}

/** Computed summary the dashboard renders without needing to recompute anything. */
export interface ImpactSummary {
  perStage: StageImpact[];
  /** Total median relay time across all stages, seconds. */
  totalRelaySec: number | null;
  /** Total median baseline time across all stages, seconds. */
  totalBaselineSec: number | null;
  /** Count of acceptance criteria marked `covered: true` across all tasks. */
  criteriaCovered: number;
  /** Total count of acceptance criteria across all tasks. */
  criteriaTotal: number;
  /** Count of cancelled/failed stage runs excluded from every duration above. */
  excludedRuns: number;
}

/**
 * The compiled snapshot written to `dashboard/public/relay-data.json` by the
 * CLI's `compile` command (Sprint 2). The dashboard is a dumb reader of this
 * single file - no server, no live queries.
 */
export interface RelayData {
  schemaVersion: number;
  /** ISO 8601 timestamp of when this snapshot was generated. */
  generatedAt: string;
  tasks: CompiledTask[];
  knowledge: KnowledgeEntry[];
  impact: ImpactSummary;
}
